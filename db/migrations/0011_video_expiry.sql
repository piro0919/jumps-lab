-- 動画は 90 日で消す（2026-10-12 に本人と決めた。中元さんのフィードバック：残す価値があるのは動画より分析の結果）。
-- 消える日を行ごとに持つ（あとでプランごとに日数を変えるため）。今ある動画は、この変更を当てた時から 90 日。
-- now() は当てた時に一度だけ計算されるので、表を書き直さない。新しい動画は src/lib/data.ts が日数を入れる。
-- 本体は R2 のライフサイクルの規則（videos/ を 91 日で消す）が消す。行は期限を過ぎたら画面に出さず、保存量にも数えない
alter table video add column "expiresAt" timestamptz not null default now() + interval '90 days';
